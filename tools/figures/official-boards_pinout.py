#!/usr/bin/env python3
"""Write the complete Proteus pinout table from the official connector yaml files.

    .venv/bin/python tools/figures/official-boards_pinout.py

Reads rusefi/firmware/config/boards/proteus/connectors/{black23,black35,white35}.yaml and writes
documentation/docs/reference/pinout/_proteus.table.md (connector, pin, function, type, TunerStudio name).
Entries without a connector pin number continue the pin above them (the VR inputs); entries whose
"pin" is an MCU pin name (PD8...) are not connector pins and are left out.
"""
import pathlib
import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT.parent / "rusefi/firmware/config/boards/proteus/connectors"
OUT = ROOT / "documentation/docs/reference/pinout/_proteus.table.md"
TYPES = {"din": "digital input", "vr": "VR input", "etb": "H-bridge (ETB)", "gnd": "power ground",
         "can": "CAN", "12v": "12 V", "hs": "high-side output", "inj": "low-side output (injector)",
         "ls": "low-side output", "ign": "ignition output (logic level)", "agnd": "sensor ground",
         "5v": "5 V sensor supply", "av": "analog voltage input", "at": "analog temperature input"}


def rows(cid):
    data = yaml.safe_load((SRC / f"{cid}.yaml").read_text())
    out = []
    for p in data["pins"]:
        pin = p.get("pin")
        if pin is None and out:            # continuation of the pin above (e.g. VR id / ts_name)
            if p.get("ts_name"):
                out[-1]["ts"] = p["ts_name"]
            continue
        if not isinstance(pin, int):       # MCU pin names such as PD8, not on the connector
            continue
        out.append({"pin": pin, "fn": str(p.get("function", "")), "type": p.get("type", ""),
                    "ts": p.get("ts_name", "")})
    return data["info"]["name"], sorted(out, key=lambda r: r["pin"])


def main():
    lines = ["| Connector | Pin | Function | Type | TunerStudio name |", "|---|---|---|---|---|"]
    for cid in ("black23", "black35", "white35"):
        name, rs = rows(cid)
        for r in rs:
            t = TYPES.get(r["type"], r["type"] or "—")
            lines.append(f"| {name} | {r['pin']} | {r['fn'].replace('|', '/')} | {t} | {r['ts'] or '—'} |")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("<!-- generated by tools/figures/official-boards_pinout.py from "
                   "firmware/config/boards/proteus/connectors/*.yaml; do not edit -->\n\n"
                   + "\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(lines) - 2} pins)")


if __name__ == "__main__":
    main()
