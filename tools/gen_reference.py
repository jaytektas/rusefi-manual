#!/usr/bin/env python3
"""Generate Part VII reference pages from the rusEFI source and the official TunerStudio ini.

    python3 -I tools/gen_reference.py

Writes (never edit these by hand; re-run after a sync):
  documentation/docs/part7/error-codes.md       every ObdCode (firmware/controllers/algo/obd_error_codes.h)
  documentation/docs/part7/console-commands.md  every console command registered with addConsoleAction*
  documentation/docs/part7/settings.md          every TunerStudio menu entry, by menu
  documentation/docs/part7/settings-<menu>.md   one page per top-level menu, with each dialog's settings table
"""
import collections
import os
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
RUSEFI = pathlib.Path(os.environ.get("RUSEFI", ROOT.parent / "rusefi"))
INI = pathlib.Path(os.environ.get("RUSEFI_INI", ROOT.parent / "tools/bundle/official/rusefi.snapshot.proteus_f7/rusefi_proteus_f7.ini"))
OUT = ROOT / "documentation/docs/part7"
SETTINGS = ROOT / "documentation/docs/reference/settings"
sys.path.insert(0, str(ROOT / "tools"))
import gen_settings  # noqa: E402

ACRONYMS = {"vvt", "etb", "tps", "map", "clt", "iat", "rpm", "can", "adc", "spi", "pwm", "obd", "ecu", "ts", "sd", "usb", "isr", "io", "pps", "afr", "ve", "maf", "pid", "lua", "dfu", "egt", "ign", "inj", "hw", "rtc", "msd", "fsio", "vss", "wbo", "ego", "iac", "idle"}
ACRONYMS.discard("idle")
GEN = "<!-- generated by tools/gen_reference.py; do not edit -->\n\n"
BADGE = ":material-circle:{ .level-advanced } Advanced\n\n"


def cell(s):
    return s.replace("|", "\\|").strip()


def error_codes():
    text = (RUSEFI / "firmware/controllers/algo/obd_error_codes.h").read_text()
    descr = {m.group(1): m.group(2).strip() for m in re.finditer(r"//\s*(P\d{4})\s+(.+)", text)}
    rows = []
    for m in re.finditer(r"^\s*([A-Za-z][A-Za-z0-9_]*)\s*=\s*(\d+)\s*,", text, re.M):
        name, num = m.group(1), int(m.group(2))
        if name == "None":
            continue
        pcode = f"P{num:04d}" if num < 10000 else ""
        words = re.sub(r"^(OBD_|CUSTOM_(ERR_|OBD_)?)", "", name).replace("_", " ")
        own = re.sub(r"(?<=[a-z])(?=[A-Z])", " ", words).strip().lower()
        own = " ".join(w.upper() if re.sub(r"\d", "", w) in ACRONYMS else w for w in own.split())
        own = own[:1].upper() + own[1:]
        # (what rusEFI reports this code for, from its name; the generic OBD-II meaning of the number)
        d = (own, descr.get(pcode, ""))
        rows.append((num, pcode, name, d))
    rows.sort()
    std = [r for r in rows if r[0] < 6000]
    cus = [r for r in rows if r[0] >= 6000]
    out = [GEN, "# Error codes\n\n", BADGE,
           "Every diagnostic and warning code rusEFI can report, from the firmware's own list. Codes below "
           "6000 follow the standard OBD-II P-code numbering (shown as `P0107` and so on); codes from 6000 up "
           "are rusEFI's own. TunerStudio shows active codes in the *Warning* indicator and the warning-code "
           "channels; the rusEFI console lists them too.\n\n",
           "<!-- src: firmware/controllers/algo/obd_error_codes.h (enum class ObdCode and the P-code comments) -->\n\n",
           f"## Standard (OBD-II) codes\n\n{len(std)} codes. *rusEFI condition* is what the firmware reports the "
           "code for, read from its name in the source; the *standard description* is the generic OBD-II meaning "
           "of that number, where the firmware lists it. The two can differ in detail.\n\n"
           "| Code | Name in firmware | rusEFI condition | Standard OBD-II description |\n|---|---|---|---|\n"]
    out += [f"| {p} | `{n}` | {cell(d[0])} | {cell(d[1]) or '—'} |\n" for _, p, n, d in std]
    out += [f"\n## rusEFI codes\n\n{len(cus)} codes. The condition is read from the firmware's name for the code.\n\n"
            "| Number | Name in firmware | rusEFI condition |\n|---|---|---|\n"]
    out += [f"| {num} | `{n}` | {cell(d[0])} |\n" for num, _, n, d in cus]
    (OUT / "error-codes.md").write_text("".join(out))
    return len(rows)


ARG_TYPES = {"I": "integer", "F": "number", "S": "text", "P": "pointer"}


def console_commands():
    cmds = []
    for f in sorted((RUSEFI / "firmware").rglob("*.cpp")):
        rel = f.relative_to(RUSEFI).as_posix()
        if any(x in rel for x in ("/ChibiOS", "/ext/", "/ChibiOS-Contrib", "controllers/can/wideband_firmware")):
            continue
        for m in re.finditer(r'addConsoleAction([A-Z]*)\(\s*"([^"]+)"', f.read_text(errors="replace")):
            suffix, name = m.group(1), m.group(2)
            args = ", ".join(ARG_TYPES.get(c, c) for c in suffix if c in ARG_TYPES) or "none"
            cmds.append((name, args, rel))
    cmds.sort(key=lambda c: (c[2].split("/")[1] if "/" in c[2] else "", c[0]))
    out = [GEN, "# Console commands\n\n", BADGE,
           "Every text command the firmware accepts, as registered in the source. Type them in the rusEFI "
           "console's command box; TunerStudio sends some of them through its own buttons. Arguments are "
           "separated by spaces. Commands for bench and factory testing drive outputs directly: read the "
           "bench-testing chapter and the safety page before using them on a connected engine.\n\n",
           "!!! danger \"Commands act immediately\"\n    Many commands switch outputs, change settings or "
           "reboot the ECU at once. On a car, injectors can spray fuel and coils can fire.\n\n",
           f"{len(cmds)} commands.\n\n| Command | Arguments | Defined in |\n|---|---|---|\n"]
    out += [f"| `{n}` | {a} | `{r}` |\n" for n, a, r in cmds]
    files = sorted({r for _, _, r in cmds})
    out.append("\n<!-- src: " + "; ".join(f"{r} (addConsoleAction calls)" for r in files[:40]) + " -->\n")
    (OUT / "console-commands.md").write_text("".join(out))
    return len(cmds)


def settings():
    text = INI.read_text(errors="replace")
    consts, helps, dialogs = gen_settings.parse(text)
    menu = gen_settings.section(text, "Menu")
    tree, current, group = collections.OrderedDict(), None, None
    for line in menu.splitlines():
        m = re.match(r'\s*menu\s*=\s*"([^"]+)"', line)
        if m:
            current, group = m.group(1).replace("&", ""), None
            tree[current] = []
            continue
        m = re.match(r'\s*(subMenu|groupChildMenu)\s*=\s*(\w+)\s*,\s*"([^"]+)"', line)
        if m and current and m.group(2) != "std_separator":
            if m.group(1) == "subMenu" and group:
                # a plain entry after a group's children sits on the menu itself, not in the group
                group = None
                tree[current].append((None, f"More {current} entries"))
            tree[current].append((m.group(2), m.group(3), group))
        m = re.match(r'\s*groupMenu\s*=\s*"([^"]+)"', line)
        if m and current:
            group = m.group(1)
            tree[current].append((None, group))
    index = [GEN, "# Every setting, by menu\n\n", BADGE,
             "The complete TunerStudio menu for a Proteus F7, with every setting in every dialog: label, "
             "internal name, units, range and the help text TunerStudio shows. Generated from the official "
             "ini; other boards add or hide a few entries.\n\n",
             "<!-- src: firmware/tunerstudio/tunerstudio.template.ini ([Menu] and dialogs); firmware/integration/rusefi_config.txt (setting definitions and help) -->\n\n"]
    wanted = []
    for top, items in tree.items():
        slug = re.sub(r"[^a-z0-9]+", "-", top.lower()).strip("-")
        page = [GEN, f"# Settings: {top} menu\n\n", BADGE,
                f"Every dialog under TunerStudio's **{top}** menu, in menu order.\n\n",
                "<!-- src: firmware/tunerstudio/tunerstudio.template.ini ([Menu] and dialogs); firmware/integration/rusefi_config.txt (setting definitions and help) -->\n\n"]
        count = 0
        for name, title, *grp in items:
            if name is None:
                page.append(f"## {title}\n\n")
                continue
            rows = gen_settings.rows_for(name, dialogs, consts, helps, set()) if name in dialogs else []
            path = " ▸ ".join([top] + [g for g in grp if g] + [title])
            page.append(f"### {title}\n\n**{path}**\n\n")
            if rows:
                wanted.append(name)
                count += len(rows)
                page.append(f'--8<-- "reference/settings/_{name}.table.md"\n\n')
            elif name in dialogs:
                page.append("This dialog holds tables, curves or buttons rather than individual settings.\n\n")
            else:
                page.append("A table, curve or tool rather than a dialog of settings.\n\n")
        (OUT / f"settings-{slug}.md").write_text("".join(page))
        index.append(f"- [{top}](settings-{slug}.md) — {len(items)} entries, {count} settings\n")
    (OUT / "settings.md").write_text("".join(index))
    subprocess.run([sys.executable, "-I", str(ROOT / "tools/gen_settings.py"), *sorted(set(wanted))],
                   check=True, capture_output=True)
    return list(tree), len(set(wanted))


OUT.mkdir(parents=True, exist_ok=True)
SETTINGS.mkdir(parents=True, exist_ok=True)
print("error codes:", error_codes())
print("console commands:", console_commands())
menus, n = settings()
print("menus:", menus, "dialogs with settings:", n)
