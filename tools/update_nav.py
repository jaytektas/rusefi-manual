def summary(path):
    m = re.search(r"\*\*In one sentence:\*\*\s*(.+?)(?:\n\n|\n[^>])", path.read_text(), re.S)
    s = re.sub(r"\s*\n>\s*", " ", m.group(1)).strip() if m else ""
    return s[:1].upper() + s[1:]


PART7_EXTRA = [("Glossary", "glossary"), ("Appendix: tuning in the rusEFI console", "console-appendix")]

yml = ROOT / "mkdocs.yml"
text = yml.read_text()
nav = ["nav:", "  - Home: index.md", "  - Read this first — safety and disclaimer: safety.md"]
for name, (part, chapters) in PARTS.items():
    nav += [f"  - {name}:", f"      - {part}/index.md"]
    written = [(t, s) for t, s in chapters if (DOCS / part / f"{s}.md").exists()]
    todo = [t for t, s in chapters if (t, s) not in written]
    nav += [f"      - {t}: {part}/{s}.md" for t, s in written]
    page = [f"<!-- GENERATED by tools/update_nav.py: edit the intro there, the summaries in the chapters. -->\n\n# {name}\n\n{INTROS[part]}\n\n"]
    page += [f"- **[{t}]({s}.md)** — {summary(DOCS / part / f'{s}.md')}\n" for t, s in written]
    if todo:
        page.append("\n**Still being written:** " + ", ".join(todo) + ".\n")
    (DOCS / part / "index.md").write_text("".join(page))

part7 = text[text.index("  - Part VII — Reference:"):].rstrip("\n").splitlines()
part7 = [l for l in part7 if not any(f"part7/{s}.md" in l for _, s in PART7_EXTRA)]
part7 += [f"      - {t}: part7/{s}.md" for t, s in PART7_EXTRA if (DOCS / "part7" / f"{s}.md").exists()]
yml.write_text(text[:text.index("nav:")] + "\n".join(nav + part7) + "\n")
print(sum(l.endswith(".md") for l in nav), "pages in Parts 0-VI")
