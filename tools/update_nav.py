#!/usr/bin/env python3
"""Rebuild the mkdocs nav and the part index pages (Parts 0-VI) from the chapters that exist.

    python3 -I tools/update_nav.py

A chapter joins the nav once its file exists. Each part index page is generated: the part's
introduction (INTROS below), then every written chapter with its own "In one sentence" summary, taken
from the chapter so the index cannot drift from it, then the chapters still to come. Part VII keeps its
generated entries; the glossary and console appendix are appended when present.
"""
